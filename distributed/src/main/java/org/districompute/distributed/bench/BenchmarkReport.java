package org.districompute.distributed.bench;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.OptionalDouble;
import java.util.function.ToDoubleFunction;
import java.util.stream.Collectors;
import org.districompute.core.execution.ExecutionMode;
import org.districompute.distributed.Json;
import org.districompute.distributed.bench.BenchmarkRunner.Results;
import org.districompute.distributed.bench.BenchmarkRunner.Sample;
import org.districompute.distributed.metrics.DistributedMetrics;
import org.districompute.distributed.metrics.WorkerShare;

/**
 * Writes {@code results.json} (every sample, with the environment) and {@code summary.md} (medians per
 * configuration). Only runs that {@linkplain Sample#counts() count} enter the summary.
 */
public final class BenchmarkReport {

    private BenchmarkReport() {
    }

    /**
     * Writes both files.
     *
     * @param results the results
     * @param directory output directory
     * @throws IOException if a file cannot be written
     */
    public static void write(Results results, Path directory) throws IOException {
        Files.createDirectories(directory);
        Files.writeString(directory.resolve("results.json"), Json.toPrettyJson(results) + "\n",
                StandardCharsets.UTF_8);
        Files.writeString(directory.resolve("summary.md"), summary(results), StandardCharsets.UTF_8);
    }

    /**
     * The Markdown summary.
     *
     * @param results the results
     * @return the summary
     */
    public static String summary(Results results) {
        StringBuilder md = new StringBuilder();
        md.append("# Benchmark summary (suite `").append(results.settings().suite()).append("`)\n\n");
        md.append("Generated by `bench`. Medians of ").append(results.settings().repeat())
                .append(" measured runs per configuration, after ").append(results.settings().warmup())
                .append(" warm-up run(s). Raw data: `results.json`.\n\n");
        md.append("| Environment | |\n|---|---|\n");
        results.environment().forEach((k, v) -> md.append("| ").append(k).append(" | ").append(v).append(" |\n"));
        md.append('\n');
        if (!results.problems().isEmpty()) {
            md.append("## Problems\n\nThese runs are excluded from the tables.\n\n");
            results.problems().forEach(p -> md.append("* ").append(p).append('\n'));
            md.append('\n');
        }
        for (Experiment experiment : results.experiments()) {
            md.append("## ").append(experiment.title()).append(" (`").append(experiment.id()).append("`)\n\n");
            md.append(experiment.question()).append("\n\n");
            md.append("| Configuration | Cores | Wall s, median (min-max) | Speedup | Efficiency | Partitions "
                    + "| Kernel sum s | Transfer sum s | Encoding sum s | Scheduling ms | Moved MiB | Utilization "
                    + "| Imbalance | Attempts per worker |\n");
            md.append("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|\n");
            for (Configuration c : experiment.configurations()) {
                md.append(row(results, experiment, c)).append('\n');
            }
            md.append('\n');
        }
        md.append("Speedup: median sequential wall time of the same workload divided by this median. Efficiency: "
                + "speedup divided by cores. Kernel, transfer and encoding sums add up the attempts' times (they "
                + "overlap in wall time). Utilization: worker execute time / (distributed wall time x slots). "
                + "Imbalance: largest per-worker kernel time / mean (1.00 = balanced).\n");
        return md.toString();
    }

    private static String row(Results results, Experiment experiment, Configuration c) {
        List<Sample> runs = results.samples().stream().filter(s -> s.experiment().equals(experiment.id())
                && s.configuration().equals(c.label()) && s.counts()).toList();
        if (runs.isEmpty()) {
            return "| " + c.label() + " | " + c.cores() + " | no verified run |  |  |  |  |  |  |  |  |  |  |  |";
        }
        double wall = median(runs, s -> s.wallNanos() / 1e9);
        double min = runs.stream().mapToDouble(s -> s.wallNanos() / 1e9).min().orElse(0);
        double max = runs.stream().mapToDouble(s -> s.wallNanos() / 1e9).max().orElse(0);
        OptionalDouble sequential = sequentialMedian(results, c.workload().name());
        String speedup = sequential.isPresent() ? f2(sequential.getAsDouble() / wall) : "";
        String efficiency = sequential.isPresent() ? f2(sequential.getAsDouble() / wall / c.cores()) : "";
        String partitions = Long.toString(Math.round(median(runs, Sample::partitions)));
        StringBuilder row = new StringBuilder();
        row.append("| ").append(c.label()).append(" | ").append(c.cores()).append(" | ")
                .append(String.format(Locale.ROOT, "%.3f (%.3f-%.3f)", wall, min, max)).append(" | ").append(speedup)
                .append(" | ").append(efficiency).append(" | ").append(partitions).append(" | ");
        if (c.mode() != ExecutionMode.DISTRIBUTED_CPU || runs.get(0).distributed() == null) {
            return row.append(" |  |  |  |  |  |  |  |").toString();
        }
        row.append(f3(median(runs, s -> s.distributed().kernelNanos() / 1e9))).append(" | ")
                .append(f3(median(runs, s -> s.distributed().transferNanos() / 1e9))).append(" | ")
                .append(f3(median(runs, s -> s.distributed().serializationNanos() / 1e9))).append(" | ")
                .append(f2(median(runs, s -> s.distributed().schedulingNanos() / 1e6))).append(" | ")
                .append(f2(median(runs, s -> (s.distributed().bytesSent() + s.distributed().bytesReceived())
                        / 1048576.0))).append(" | ")
                .append(f2(median(runs, s -> s.distributed().workerUtilization()))).append(" | ")
                .append(f2(median(runs, s -> s.distributed().loadImbalance()))).append(" | ")
                .append(shares(medianRun(runs).distributed())).append(" |");
        return row.toString();
    }

    private static OptionalDouble sequentialMedian(Results results, String workload) {
        List<Sample> runs = results.samples().stream().filter(s -> s.workload().equals(workload)
                && s.mode() == ExecutionMode.SEQUENTIAL_CPU && s.counts()).toList();
        return runs.isEmpty() ? OptionalDouble.empty() : OptionalDouble.of(median(runs, s -> s.wallNanos() / 1e9));
    }

    private static String shares(DistributedMetrics metrics) {
        return metrics.perWorker().stream().sorted(Comparator.comparing(WorkerShare::workerId))
                .map(w -> w.workerId() + " " + w.succeeded()).collect(Collectors.joining(", "));
    }

    private static Sample medianRun(List<Sample> runs) {
        List<Sample> sorted = runs.stream().sorted(Comparator.comparingLong(Sample::wallNanos)).toList();
        return sorted.get((sorted.size() - 1) / 2);
    }

    static double median(List<Sample> runs, ToDoubleFunction<Sample> value) {
        double[] values = runs.stream().mapToDouble(value).sorted().toArray();
        int n = values.length;
        return n % 2 == 1 ? values[n / 2] : (values[n / 2 - 1] + values[n / 2]) / 2;
    }

    private static String f2(double v) {
        return String.format(Locale.ROOT, "%.2f", v);
    }

    private static String f3(double v) {
        return String.format(Locale.ROOT, "%.3f", v);
    }
}
