package org.districompute.distributed.coordinator;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import javax.net.ssl.SSLException;
import org.districompute.distributed.communication.TlsConfig;
import org.districompute.distributed.protocol.MessageType;
import org.districompute.distributed.testing.CoreFixtures;
import org.districompute.distributed.testing.ProtocolClient;
import org.districompute.distributed.testing.TlsFixtures;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** Registration over TLS with a certificate generated by keytool. */
@Tag("integration")
class TlsRegistrationTest {

    @Test
    void workersRegisterOverTlsAndPlainClientsCannot(@TempDir Path dir) throws IOException {
        TlsConfig[] tls = TlsFixtures.create(dir);
        try (Coordinator coordinator = Coordinator.start(CoordinatorRegistrationTest.config().tls(tls[0]).build())) {
            try (ProtocolClient client = ProtocolClient.connect(tls[1], "127.0.0.1", coordinator.port())) {
                assertEquals(MessageType.REGISTER_ACK, client.register("tls-worker",
                        CoordinatorRegistrationTest.SECRET, CoreFixtures.capabilities(1)).type());
            }
            try (ProtocolClient plain = ProtocolClient.connect(coordinator.port())) {
                plain.sendRaw("{\"protocolVersion\":\"0.1\"}");
                assertTrue(plain.awaitClosed(Duration.ofSeconds(5)), "plain TCP is refused by the TLS port");
            }
            assertEquals(1, coordinator.workers().size());
        }
    }

    @Test
    void workersRefuseACoordinatorTheyDoNotTrust(@TempDir Path dir) throws IOException {
        Path ours = Files.createDirectories(dir.resolve("ours"));
        Path other = Files.createDirectories(dir.resolve("other"));
        TlsConfig coordinatorTls = TlsFixtures.create(ours)[0];
        TlsConfig strangerTrust = TlsFixtures.create(other)[1];
        try (Coordinator coordinator = Coordinator.start(CoordinatorRegistrationTest.config().tls(coordinatorTls)
                .build())) {
            assertThrows(SSLException.class,
                    () -> ProtocolClient.connect(strangerTrust, "127.0.0.1", coordinator.port()));
        }
    }
}
